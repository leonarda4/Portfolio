import { createHash, randomUUID, timingSafeEqual } from 'node:crypto'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { DRAWING_COLORS } from '../src/components/playful/brush.js'

const validPage = page => typeof page === 'string' && /^(\/|\/about|\/project\/[a-z0-9-]{1,80})$/.test(page)
const validId = id => typeof id === 'string' && /^[a-f0-9-]{36}$/i.test(id)
const error = (status, message) => Object.assign(new Error(message), { status })
const publicStroke = ({ editHash, ...stroke }) => stroke
function keyHash(key) {
  if (!validId(key)) throw error(403, 'This drawing is not editable in this visit.')
  return createHash('sha256').update(key).digest('hex')
}
function authorize(stroke, key) {
  if (!timingSafeEqual(Buffer.from(stroke.editHash, 'hex'), Buffer.from(keyHash(key), 'hex'))) throw error(403, 'This drawing is not editable in this visit.')
}

export function validateDrawing(input) {
  if (!input || !validId(input.id) || !validPage(input.page)) throw error(400, 'Invalid drawing or page.')
  if (!DRAWING_COLORS.includes(input.color)) throw error(400, 'Choose a crayon color.')
  // Only the filled paths generated by our brush, never SVG markup or URLs.
  if (typeof input.path !== 'string' || input.path.length > 250000 || !/^M[0-9MQaZ.,\s+-]+Z$/.test(input.path)) throw error(400, 'Invalid drawing stroke.')
  const numbers = input.path.match(/[+-]?(?:\d+\.?\d*|\.\d+)/g) || []
  if (!numbers.length || numbers.some(value => !Number.isFinite(Number(value)) || Math.abs(Number(value)) > 500000)) throw error(400, 'Invalid drawing coordinates.')
  const p = input.placement
  const inRange = (value, min, max) => Number.isFinite(value) && value >= min && value <= max
  if (!p || !/^(page|intro|case-cover|about-page|footer|id:[a-z0-9-]{1,100}|project:#\/project\/[a-z0-9-]{1,80})$/.test(p.anchor)
    || !inRange(p.x, 0, 1) || !inRange(p.y, 0, p.anchor === 'page' ? 500000 : 1)
    || !inRange(p.width, 1, 20000) || !inRange(p.fallbackX, 0, 1) || !inRange(p.fallbackY, 0, 500000)) throw error(400, 'Invalid drawing position.')
  return { id: input.id, page: input.page, color: input.color, path: input.path, placement: { anchor: p.anchor, x: p.x, y: p.y, width: p.width, fallbackX: p.fallbackX, fallbackY: p.fallbackY } }
}

export function createDrawingStore(file = resolve(process.env.DRAWING_DATA_FILE || '.data/drawings.json')) {
  let queue = Promise.resolve()
  async function read() {
    try {
      const strokes = JSON.parse(await readFile(file, 'utf8'))
      if (!Array.isArray(strokes)) throw new Error('Drawing data must be an array.')
      return strokes
    } catch (cause) { if (cause.code === 'ENOENT') return []; throw cause }
  }
  async function write(strokes) {
    await mkdir(dirname(file), { recursive: true })
    const temporary = `${file}.${randomUUID()}.tmp`
    await writeFile(temporary, `${JSON.stringify(strokes)}\n`, { mode: 0o600 })
    await rename(temporary, file)
  }
  function transaction(work) {
    const operation = queue.then(work)
    queue = operation.catch(() => {})
    return operation
  }
  return {
    async list(page) { await queue; return (await read()).filter(stroke => stroke.page === page).map(publicStroke) },
    add(input, key) {
      const stroke = validateDrawing(input)
      const editHash = keyHash(key)
      return transaction(async () => {
        const strokes = await read()
        const existing = strokes.find(item => item.id === stroke.id)
        if (existing) { authorize(existing, key); return publicStroke(existing) }
        const pageStrokes = strokes.filter(item => item.page === stroke.page)
        if (pageStrokes.length >= 2000 || pageStrokes.reduce((size, item) => size + item.path.length, stroke.path.length) > 20000000) throw error(409, 'This page’s drawing board is full. Thank you for visiting!')
        const saved = { ...stroke, createdAt: new Date().toISOString(), editHash }
        await write([...strokes, saved])
        return publicStroke(saved)
      })
    },
    remove(id, key) {
      keyHash(key)
      return transaction(async () => {
        const strokes = await read()
        const existing = strokes.find(item => item.id === id)
        if (!existing) return
        authorize(existing, key)
        await write(strokes.filter(item => item.id !== id))
      })
    },
  }
}

export function createDrawingHandler({ store = createDrawingStore(), limit = 300 } = {}) {
  const writes = new Map()
  return async (request, response, next) => {
    const url = new URL(request.url, 'http://localhost')
    const item = url.pathname.match(/^\/api\/drawings\/([a-f0-9-]{36})$/i)
    if (url.pathname !== '/api/drawings' && !item) { if (next) return next(); response.writeHead(404).end(); return }
    const send = (status, data) => { response.writeHead(status, { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff' }); response.end(JSON.stringify(data)) }
    try {
      if (request.method === 'GET' && !item) {
        const page = url.searchParams.get('page')
        if (!validPage(page)) throw error(400, 'Invalid page.')
        send(200, { drawings: await store.list(page) }); return
      }
      if (item ? request.method !== 'DELETE' : request.method !== 'POST') { response.setHeader('Allow', item ? 'DELETE' : 'GET, POST'); throw error(405, 'Method not supported.') }
      if (!request.headers['content-type']?.startsWith('application/json')) throw error(415, 'Send a JSON drawing.')
      if (request.headers.origin && new URL(request.headers.origin).host !== request.headers.host) throw error(403, 'Save drawings from this website.')
      const key = request.headers['x-drawing-key']
      if (item) { await store.remove(item[1], key); send(200, { deleted: true }); return }
      const now = Date.now()
      for (const [address, bucket] of writes) if (bucket.expires <= now) writes.delete(address)
      const address = request.socket.remoteAddress
      const bucket = writes.get(address) || { count: 0, expires: now + 3600000 }
      if (bucket.count >= limit) { response.setHeader('Retry-After', String(Math.ceil((bucket.expires - now) / 1000))); throw error(429, 'Please try drawing again in a little while.') }
      let body = ''
      for await (const chunk of request) {
        body += chunk
        if (Buffer.byteLength(body) > 260000) throw error(413, 'That stroke is too long. Try shorter strokes.')
      }
      let input
      try { input = JSON.parse(body) } catch { throw error(400, 'Invalid drawing data.') }
      const drawing = await store.add(input, key)
      bucket.count += 1; writes.set(address, bucket)
      send(201, { drawing })
    } catch (cause) {
      if (!cause.status) console.error('Drawing storage error:', cause.message)
      send(cause.status || 503, { error: cause.status ? cause.message : 'Couldn’t save your drawing. Your draft is still here. Please try again.' })
    }
  }
}
